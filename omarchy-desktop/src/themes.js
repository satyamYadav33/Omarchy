export class ThemeManager {
  constructor(defaultTheme = "tokyo-night") {
    this.currentThemeName = defaultTheme;
    this.currentWallpaperIndex = 0;
    this.subscribers = [];
  }

  get currentTheme() {
    return THEMES[this.currentThemeName] || THEMES["tokyo-night"];
  }

  setTheme(themeName) {
    if (!THEMES[themeName]) return false;
    this.currentThemeName = themeName;
    this.currentWallpaperIndex = 0;
    this.applyTheme();
    this.notify();
    return true;
  }

  setWallpaper(pathOrIndex) {
    const theme = this.currentTheme;
    if (typeof pathOrIndex === "number") {
      this.currentWallpaperIndex = pathOrIndex % theme.wallpapers.length;
    } else {
      const idx = theme.wallpapers.indexOf(pathOrIndex);
      if (idx !== -1) this.currentWallpaperIndex = idx;
    }
    this.applyWallpaper();
    this.notify();
  }

  nextWallpaper() {
    const theme = this.currentTheme;
    this.currentWallpaperIndex = (this.currentWallpaperIndex + 1) % theme.wallpapers.length;
    this.applyWallpaper();
    this.notify();
  }

  applyTheme() {
    const theme = this.currentTheme;
    const root = document.documentElement;

    root.style.setProperty("--theme-mode", theme.mode);
    root.style.setProperty("--theme-accent", theme.accent);
    root.style.setProperty("--theme-selection", theme.selection);
    root.style.setProperty("--theme-muted", theme.muted);
    root.style.setProperty("--theme-background", theme.background);
    root.style.setProperty("--theme-dark-background", theme.dark_background);
    root.style.setProperty("--theme-darker-background", theme.darker_background);
    root.style.setProperty("--theme-lighter-background", theme.lighter_background);
    root.style.setProperty("--theme-foreground", theme.foreground);
    root.style.setProperty("--theme-dark-foreground", theme.dark_foreground);
    root.style.setProperty("--theme-light-foreground", theme.light_foreground);
    root.style.setProperty("--theme-bright-foreground", theme.bright_foreground);
    root.style.setProperty("--theme-red", theme.red);
    root.style.setProperty("--theme-yellow", theme.yellow);
    root.style.setProperty("--theme-orange", theme.orange);
    root.style.setProperty("--theme-green", theme.green);
    root.style.setProperty("--theme-cyan", theme.cyan);
    root.style.setProperty("--theme-blue", theme.blue);
    root.style.setProperty("--theme-magenta", theme.magenta);

    // Dynamic Hyprland glowing border
    const borderGradient = `linear-gradient(135deg, ${theme.accent}ee, ${theme.magenta || theme.cyan || theme.accent}aa)`;
    root.style.setProperty("--hypr-active-border", borderGradient);

    this.applyWallpaper();
  }

  applyWallpaper() {
    const theme = this.currentTheme;
    const wallpaperPath = theme.wallpapers[this.currentWallpaperIndex] || theme.wallpaper;
    const wallpaperElem = document.getElementById("omarchy-wallpaper");
    if (wallpaperElem) {
      wallpaperElem.style.backgroundImage = `url('${wallpaperPath}')`;
    }
  }

  subscribe(callback) {
    this.subscribers.push(callback);
    callback(this.currentTheme);
  }

  notify() {
    for (const sub of this.subscribers) {
      try {
        sub(this.currentTheme);
      } catch (e) {
        console.error(e);
      }
    }
  }
}
